/** Saves generated text (exports, API keys) as a file in the browser. */

/** Triggers a download of `body` as `filename`. */
export const downloadText = (filename: string, body: string, mime = 'text/plain') => {
  const url = URL.createObjectURL(new Blob([body], { type: `${mime};charset=utf-8` }))
  const link = document.createElement('a')
  link.href = url
  link.download = filename
  document.body.append(link)
  link.click()
  link.remove()
  setTimeout(() => URL.revokeObjectURL(url), 1000)
}
