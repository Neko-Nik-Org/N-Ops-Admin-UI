/** Shared React Query client and its default caching behavior. */

import { QueryClient } from '@tanstack/react-query'

/** Queries retry once, stay fresh for a minute, and do not refetch on window focus. */
export const queryClient = new QueryClient({
  defaultOptions: {
    queries: {
      retry: 1,
      staleTime: 60_000,
      refetchOnWindowFocus: false,
    },
  },
})
